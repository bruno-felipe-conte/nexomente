const getInitialLocale = () => {
  if (typeof window === 'undefined') return 'pt-BR';
  const saved = localStorage.getItem('nexomente_locale');
  if (saved && DICTIONARIES[saved]) return saved;
  return 'pt-BR';
};

export const useI18nStore = create((set, get) => ({
  locale: getInitialLocale(),
  setLocale: (newLocale) => {
    if (!DICTIONARIES[newLocale]) return;
    if (typeof window !== 'undefined') {
      localStorage.setItem('nexomente_locale', newLocale);
    }
    set({ locale: newLocale });
  },
  t: (key, fallback) => {
    const { locale } = get();
    const dict = DICTIONARIES[locale] || DICTIONARIES['pt-BR'];
    return dict[key] || DICTIONARIES['pt-BR'][key] || fallback || key;
  },
}));

export function useTranslation() {
  const locale = useI18nStore((s) => s.locale);
  const setLocale = useI18nStore((s) => s.setLocale);
  const t = useI18nStore((s) => s.t);
  return { t, locale, setLocale };
}
