const getInitialLocale = () => {
  if (typeof window === 'undefined') return 'pt-BR';
  const saved = localStorage.getItem('nexomente_locale');
  if (saved && DICTIONARIES[saved]) return saved;
  return 'pt-BR';
};

export const useI18nStore = create((set, get) => ({
  locale: getInitialLocale(),
  setLocale: (newLocale) => {
    if (!DICTIONARIES[newLocale]) return;
    if (typeof window !== 'undefined') {
      localStorage.setItem('nexomente_locale', newLocale);
    }
    set({ locale: newLocale });
  },
  t: (key, fallbackOrParams, maybeParams) => {
    const { locale } = get();
    const dict = DICTIONARIES[locale] || DICTIONARIES['pt-BR'];
    let str = dict[key] || DICTIONARIES['pt-BR']?.[key];
    let params = null;

    if (typeof fallbackOrParams === 'object' && fallbackOrParams !== null) {
      params = fallbackOrParams;
    } else if (typeof fallbackOrParams === 'string') {
      if (!str) str = fallbackOrParams;
      if (typeof maybeParams === 'object' && maybeParams !== null) {
        params = maybeParams;
      }
    }

    if (!str) str = key;

    if (params) {
      Object.entries(params).forEach(([k, v]) => {
        str = str.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v));
      });
    }

    return str;
  },
}));

export function useTranslation() {
  const locale = useI18nStore((s) => s.locale);
  const setLocale = useI18nStore((s) => s.setLocale);
  const t = useI18nStore((s) => s.t);
  return { t, locale, setLocale };
}
